import { test, expect } from '@playwright/test'
import { enterApp, navigate, openReading, exitPaper } from './helpers'

test('optional date and self-described foundation yield a reasoned recommendation and survive reload', async ({ page }) => {
  await page.goto('/')
  const date = new Date()
  date.setDate(date.getDate() + 7)
  const target = `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}-${String(date.getDate()).padStart(2, '0')}`
  await page.getByLabel('考试日期（可选）', { exact: true }).fill(target)
  await page.getByLabel('自述基础（可选）', { exact: true }).selectOption('building')
  await page.getByRole('button', { name: '下一步', exact: true }).click()
  await page.getByRole('button', { name: '下一步', exact: true }).click()
  await page.getByRole('button', { name: '开始冒险', exact: true }).click()
  const focus = page.getByRole('region', { name: '本周建议主攻', exact: true })
  await expect(focus).toContainText('考前冲刺')
  await expect(focus).toContainText('7 天')
  await expect(focus).toContainText(/推荐|建议/)
  await page.reload()
  await expect(focus).toContainText('考前冲刺')
  await expect(focus).toContainText('7 天')
  await page.getByRole('button', { name: '设置', exact: true }).last().click()
  date.setDate(date.getDate() + 63)
  const later = `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}-${String(date.getDate()).padStart(2, '0')}`
  await page.getByLabel('考试日期（可选）', { exact: true }).fill(later)
  await page.getByLabel('自述基础（可选）', { exact: true }).selectOption('steady')
  await expect.poll(async () => page.evaluate(async () => {
    const connection = await new Promise<IDBDatabase>(resolve => { const request = indexedDB.open('wordquest'); request.onsuccess = () => resolve(request.result) })
    const profile = await new Promise<{ examDate: string; cetFoundation: string }>(resolve => { const request = connection.transaction('profile').objectStore('profile').get('me'); request.onsuccess = () => resolve(request.result) })
    connection.close()
    return { examDate: profile.examDate, cetFoundation: profile.cetFoundation }
  })).toEqual({ examDate: later, cetFoundation: 'steady' })
  await page.reload()
  await expect(focus).toContainText('专项突破')
})

test('skipping preferences remains usable and pending questions with analysis guide both Today and Stats', async ({ page }) => {
  await enterApp(page)
  const focus = page.getByRole('region', { name: '本周建议主攻', exact: true })
  await expect(focus).toContainText('基础积累')
  await expect(focus).toContainText(/未.*日期|没有.*日期/)
  await openReading(page)
  await page.getByRole('button', { name: '阅读 46–55', exact: true }).click()
  await page.locator('#ready-q-46 input[value="A"]').check()
  await page.getByRole('button', { name: '提交核对', exact: true }).click()
  await page.getByRole('button', { name: '确认核对 1 题', exact: true }).click()
  await exitPaper(page)
  await navigate(page, '听力')
  await page.getByRole('button', { name: /(?:开始|继续)2026年6月四级.*听力/ }).click()
  await page.locator('#ready-q-1 input[value="A"]').check()
  await page.getByRole('button', { name: '提交核对', exact: true }).click()
  await page.getByRole('button', { name: '确认核对 1 题', exact: true }).click()
  await exitPaper(page)
  await navigate(page, '今日')
  await expect(focus).toContainText('仔细阅读')
  await expect(focus).toContainText(/解析/)
  await expect(focus).toContainText(/待.*核验/)
  await navigate(page, '统计')
  await expect(page.locator('.cet-progress-report')).toContainText('仔细阅读')
  await expect(page.locator('.cet-progress-report')).toContainText(/优先|建议|下一步/)
})
