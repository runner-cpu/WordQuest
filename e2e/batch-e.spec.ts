import { test, expect } from '@playwright/test'
import { enterApp, openReading, exitPaper } from './helpers'

test('writing versions retain their own text, reasons and text-bound checks after reload', async ({ page }) => {
  await enterApp(page)
  await openReading(page)
  await page.getByRole('button', { name: '写作 30 分钟', exact: true }).click()
  const initial = 'Students can learn from their daily experiences.\n\nA reading group helps us share ideas.'
  const revised = 'Students can learn from their daily experiences.\n\nA weekly reading group helps us exchange ideas and reflect on them.'
  await page.getByLabel('我的写作草稿', { exact: true }).fill(initial)
  await page.getByText('修改原因与逐项自检', { exact: true }).click()
  const initialChecks = page.getByRole('group', { name: '逐项检查初稿', exact: true }).getByRole('checkbox')
  for (let i = 0; i < 3; i++) await initialChecks.nth(i).check()
  await expect(page.getByText('初稿三项自检对应当前文本。', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '修订稿', exact: true }).click()
  await page.getByRole('button', { name: '复制初稿开始修订', exact: true }).click()
  await page.getByLabel('我的写作修订稿', { exact: true }).fill(revised)
  await page.getByRole('button', { name: '搭配', exact: true }).click()
  const checks = page.getByRole('group', { name: '逐项检查修订稿', exact: true }).getByRole('checkbox')
  for (let i = 0; i < 3; i++) await checks.nth(i).check()
  await expect(page.getByText('修订稿三项自检对应当前文本。', { exact: true })).toBeVisible()
  await page.getByLabel('我的写作修订稿', { exact: true }).fill(`${revised} We can improve together.`)
  for (let i = 0; i < 3; i++) await expect(checks.nth(i)).not.toBeChecked()
  await page.getByText('查看参考范文与思路', { exact: true }).click()
  await page.getByRole('button', { name: /^参考句 1：/ }).click()
  await expect(page.getByText('段落数量不同或缺少文本，请手动选择要核对的段落；系统不判断内容是否对应。', { exact: true })).toBeVisible()
  await page.getByLabel('手动选择修订稿段落', { exact: true }).selectOption('1')
  await expect(page.locator('mark')).toContainText('A weekly reading group')
  await page.getByRole('button', { name: '初稿', exact: true }).click()
  await expect(page.getByLabel('我的写作草稿', { exact: true })).toHaveValue(initial)
  for (let i = 0; i < 3; i++) await expect(initialChecks.nth(i)).toBeChecked()
  await exitPaper(page)
  await page.reload()
  await openReading(page)
  await page.getByRole('button', { name: '写作 30 分钟', exact: true }).click()
  await expect(page.getByLabel('我的写作草稿', { exact: true })).toHaveValue(initial)
  await page.getByRole('button', { name: '修订稿', exact: true }).click()
  await expect(page.getByLabel('我的写作修订稿', { exact: true })).toHaveValue(`${revised} We can improve together.`)
  await page.getByText('修改原因与逐项自检', { exact: true }).click()
  await expect(page.getByRole('button', { name: '搭配', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: '翻译 30 分钟', exact: true }).click()
  await expect(page.getByLabel('我的翻译草稿', { exact: true })).toHaveValue('')
})

test('original writing preserves the submitted initial snapshot while saving a revision on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await enterApp(page)
  await page.getByRole('button', { name: '原创专项', exact: true }).click()
  await page.getByRole('group', { name: '选择四六级专项', exact: true }).getByRole('button', { name: /写作/ }).click()
  await page.getByRole('button', { name: '练习给共享自习室提一条建议', exact: true }).click()
  const initial = 'I suggest opening the study room earlier because many students want to read quietly before their morning classes begin on campus.'
  await page.getByLabel('我的英文初稿', { exact: true }).fill(initial)
  await page.getByRole('button', { name: '完成初稿，看参考', exact: true }).click()
  const checks = page.getByRole('group', { name: '逐项检查初稿', exact: true }).getByRole('checkbox')
  for (let i = 0; i < 3; i++) await checks.nth(i).check()
  await page.getByRole('button', { name: '完成自查，保存本次练习', exact: true }).click()
  await expect(page.getByRole('button', { name: '当前稿已完成自查', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '修订稿', exact: true }).click()
  await page.getByRole('button', { name: '复制初稿开始修订', exact: true }).click()
  await page.getByLabel('我的写作修订稿', { exact: true }).fill(`${initial} An earlier opening time would help us plan our study.`)
  await page.getByRole('button', { name: '时态', exact: true }).click()
  await page.getByRole('button', { name: '保存并返回', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.reload()
  await page.getByRole('button', { name: '原创专项', exact: true }).click()
  await page.getByRole('group', { name: '选择四六级专项', exact: true }).getByRole('button', { name: /写作/ }).click()
  await page.getByRole('button', { name: '练习给共享自习室提一条建议', exact: true }).click()
  await expect(page.getByLabel('我的英文初稿', { exact: true })).toHaveValue(initial)
  await page.getByRole('button', { name: '修订稿', exact: true }).click()
  await expect(page.getByLabel('我的写作修订稿', { exact: true })).toHaveValue(`${initial} An earlier opening time would help us plan our study.`)
  await expect(page.getByRole('button', { name: '时态', exact: true })).toHaveAttribute('aria-pressed', 'true')
  expect(await page.getByRole('dialog').evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
})
